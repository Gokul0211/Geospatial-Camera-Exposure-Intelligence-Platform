"use client";
import * as React from "react";
import { Button } from "@/components/ui/button";
import { InlineError } from "@/components/ui/inline-error";
import { Badge } from "@/components/ui/badge";
import { ApiError } from "@/lib/api/errors";
import { streamBrief } from "@/lib/api/sse";
import { useNews } from "@/lib/api/console-hooks";
import type { Device } from "@/lib/api/normalize";
import type { Zone } from "@/components/map/map-view";

/** Streams a zone brief from POST /api/brief/stream, built from the zone's real devices (spec 10.5). */
export function ZoneBrief({ zone, devices, city, onClear }: { zone: Zone; devices: Device[]; city: string; onClear: () => void }) {
  const inZone = React.useMemo(() => devices.filter((d) => zone.ids.includes(d.id)), [devices, zone.ids]);
  const news = useNews(city);
  const [text, setText] = React.useState("");
  const [state, setState] = React.useState<"idle" | "streaming" | "done" | "error">("idle");
  const [error, setError] = React.useState<string | null>(null);
  const abort = React.useRef<AbortController | null>(null);
  React.useEffect(() => () => abort.current?.abort(), []);

  async function run() {
    abort.current?.abort();
    const ac = new AbortController();
    abort.current = ac;
    setText("");
    setError(null);
    setState("streaming");
    const count = (xs: (string | null | undefined)[]) => xs.reduce<Record<string, number>>((m, x) => ({ ...m, [x ?? "unknown"]: (m[x ?? "unknown"] ?? 0) + 1 }), {});
    try {
      const body = {
        cluster_id: `zone-${zone.center[0].toFixed(3)}-${zone.center[1].toFixed(3)}`,
        city: city === "All India" ? "India" : city,
        device_count: inZone.length,
        device_types: [...new Set(inZone.map((d) => d.device_type ?? "unknown"))],
        manufacturers: [...new Set(inZone.map((d) => d.manufacturer ?? "unknown"))],
        owner_types: count(inZone.map((d) => d.owner_type)),
        nearby_news_headlines: (news.data?.articles ?? []).slice(0, 3).map((a) => a.title),
        area_description: `Circle of radius ${Math.round(zone.radiusM)} m around ${zone.center[1].toFixed(3)}, ${zone.center[0].toFixed(3)}`,
      };
      for await (const m of streamBrief(body, ac.signal)) {
        if (m.type === "text" || m.type === "chunk") setText((t) => t + m.content);
        else if (m.type === "error") { setError(m.message); setState("error"); return; }
        else if (m.type === "done") setState("done");
      }
      setState((s) => (s === "streaming" ? "done" : s));
    } catch (e) {
      if (e instanceof DOMException && e.name === "AbortError") return;
      setError(e instanceof ApiError ? e.detail : "The brief failed.");
      setState("error");
    }
  }

  return (
    <div className="flex flex-col gap-4 p-4">
      <header className="flex items-start justify-between gap-3">
        <div><h2 className="text-lg font-semibold tracking-tight">Zone brief</h2><p className="num text-sm text-bone-2">{inZone.length} devices in {Math.round(zone.radiusM)} m</p></div>
        <Button size="sm" variant="ghost" onClick={onClear}>Clear zone</Button>
      </header>
      <Badge className="self-start" dashed>Generated by a language model from the devices in this zone</Badge>
      <Button size="sm" className="self-start" onClick={run} disabled={state === "streaming" || inZone.length === 0}>{state === "streaming" ? "Streaming" : text ? "Regenerate" : "Generate brief"}</Button>
      {inZone.length === 0 && <p className="text-sm text-bone-2">No loaded devices fall inside this circle. Draw a larger zone.</p>}
      <div aria-live="polite" className="min-h-24 whitespace-pre-wrap text-sm leading-relaxed text-bone">{text}{state === "streaming" && <span className="ml-0.5 inline-block h-4 w-1.5 translate-y-0.5 bg-signal" aria-hidden="true" />}</div>
      {error && <InlineError title="The model returned an error">{error}</InlineError>}
    </div>
  );
}
