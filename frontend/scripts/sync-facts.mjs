// paper/data/results.json -> src/lib/content/facts.generated.ts (spec 3.4).
// Every marketing number comes from this file. Never edit the output by hand.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = (p) => fileURLToPath(new URL(p, import.meta.url));
const raw = readFileSync(root("../../paper/data/results.json"), "utf8");
const r = JSON.parse(raw);
const sha = createHash("sha256").update(raw).digest("hex");

const pick = (m) => ({
  n: m.n, tp: m.tp, fp: m.fp, tn: m.tn, fn: m.fn,
  accuracy: m.accuracy, accuracyCi: m.accuracy_ci,
  precision: m.precision, recall: m.recall, specificity: m.specificity, f1: m.f1,
});
const stratPick = (key) => ({
  n: r.stratified.WA[key].n,
  WA: r.stratified.WA[key].accuracy,
  Advanced: r.stratified.Advanced[key].accuracy,
  Bayesian: r.stratified.Bayesian[key].accuracy,
  "IG-DCTF": r.stratified["IG-DCTF"][key].accuracy,
});
const f = (value, section, path) => ({ value, source: `paper/data/results.json#${path}`, section });

const facts = {
  "res.corpus": f({ n: r.n_direct, fabricated: r.n_fabricated, genuine: r.n_genuine, withChannelB: r.n_with_signal_fields }, "results.md, Corpus", "n_direct"),
  "res.model.wa": f(pick(r.comparison.WA), "results.md section 1", "comparison.WA"),
  "res.model.advanced": f(pick(r.comparison.Advanced), "results.md section 1", "comparison.Advanced"),
  "res.model.bayesian": f(pick(r.comparison.Bayesian), "results.md section 1", "comparison.Bayesian"),
  "res.model.igdctf": f(pick(r.comparison["IG-DCTF"]), "results.md section 1", "comparison.IG-DCTF"),
  "res.mcnemar": f({ igOnly: r.mcnemar_ig_vs_adv.ig_only_correct, advOnly: r.mcnemar_ig_vs_adv.adv_only_correct, p: r.mcnemar_ig_vs_adv.p_value }, "results.md section 1", "mcnemar_ig_vs_adv"),
  "res.strat.with_b": f(stratPick("with_signal"), "results.md section 1, stratified", "stratified.*.with_signal"),
  "res.strat.without_b": f(stratPick("without_signal"), "results.md section 1, stratified", "stratified.*.without_signal"),
  "res.ablation": f(
    Object.fromEntries(Object.entries(r.ablation).map(([k, m]) => [k, { ...pick(m) }])),
    "results.md section 2", "ablation"),
  "res.sweep": f({ bestF1: r.sweep_summary.best_f1, chosenF1: r.sweep_summary.chosen_f1, within001: r.sweep_summary["within_0.01_of_best"], total: r.sweep_summary.total }, "results.md section 3", "sweep_summary"),
  "res.tier1": f({ n: r.tier1.n, tp: r.tier1.tp, fp: r.tier1.fp, tn: r.tier1.tn, fn: r.tier1.fn, precision: r.tier1.precision, recall: r.tier1.recall, msPerDevice: r.tier1.ms_per_device, distinctCases: r.tier1.distinct_cases, categories: r.tier1.categories }, "results.md section 4", "tier1"),
  "res.tier2": f({ n: r.tier2.n, tp: r.tier2.tp, fp: r.tier2.fp, tn: r.tier2.tn, fn: r.tier2.fn, precision: r.tier2.precision, recall: r.tier2.recall, meanLatencyFrames: r.tier2.mean_latency_frames }, "results.md section 5", "tier2"),
  "res.t2.end2end": f(r.tier2.categories, "results.md section 5", "tier2.categories"),
  "res.t2.single": f(r.single_factor, "results.md section 5", "single_factor"),
  "res.overhead": f({ channelAOnlyUs: r.latency_us.advanced, igdctfUs: r.latency_us.ig_dctf }, "results.md section 6", "latency_us"),
  "res.errors": f({ igdctf: r.ig_errors, advanced: r.adv_errors }, "results.md section 1", "ig_errors"),
};

const header = `// GENERATED by scripts/sync-facts.mjs from paper/data/results.json. DO NOT EDIT.
// Run \`npm run sync\` after the results change. A test fails when this file is stale.
`;
const body = `${header}
export interface Fact<T> {
  readonly value: T;
  /** File and path inside it that the value was read from. */
  readonly source: string;
  /** Section of paper/results.md the figure appears in. */
  readonly section: string;
}

export const RESULTS_JSON_SHA256 = ${JSON.stringify(sha)};

export const generatedFacts = ${JSON.stringify(facts, null, 2)} as const;

export type GeneratedFactKey = keyof typeof generatedFacts;
`;
mkdirSync(root("../src/lib/content"), { recursive: true });
writeFileSync(root("../src/lib/content/facts.generated.ts"), body);
console.log(`sync-facts: ${Object.keys(facts).length} facts, sha256 ${sha.slice(0, 12)}`);
