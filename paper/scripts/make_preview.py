"""Build paper/figures_preview.tex: all ten figures in ONE document (one figure per page).

The standalone figure files are the deliverables (one PDF each). This preview exists so the whole set can be
reviewed with a single Overleaf compile. Each figure keeps its own styles in a TeX group, so style names that
differ between figures do not clash.

Run from the repository root:  python paper/scripts/make_preview.py
"""
import glob
import os
import re

BS = chr(92)
PAPER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def grab_blocks(text: str, command: str) -> list[str]:
    """Return every `\\command{...}` block (balanced braces) found in text."""
    blocks, start = [], 0
    needle = BS + command + "{"
    while True:
        i = text.find(needle, start)
        if i < 0:
            return blocks
        depth, j = 0, i + len(BS + command)
        while j < len(text):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        blocks.append(text[i:j + 1])
        start = j + 1


def strip_comments(text: str) -> str:
    out = []
    for line in text.splitlines():
        k = 0
        while k < len(line):
            if line[k] == "%" and (k == 0 or line[k - 1] != BS):
                line = line[:k]
                break
            k += 1
        out.append(line)
    return "\n".join(out)


files = sorted(glob.glob(os.path.join(PAPER, "figures", "fig*.tex")))
libs, color_lines, pages = set(), [], []
for path in files:
    raw = open(path, encoding="utf-8").read()
    name = os.path.basename(path)
    head, body = raw.split(BS + "begin{document}", 1)
    body = body.rsplit(BS + "end{document}", 1)[0]
    head_nc = strip_comments(head)
    for blk in grab_blocks(head_nc, "usetikzlibrary"):
        libs.update(x.strip() for x in blk[len(BS + "usetikzlibrary{"):-1].split(","))
    for line in head_nc.splitlines():
        if line.strip().startswith((BS + "definecolor", BS + "colorlet")) and line.strip() not in color_lines:
            color_lines.append(line.strip())
    local = "\n".join(grab_blocks(head_nc, "tikzset") + grab_blocks(head_nc, "pgfplotsset"))
    local = local.replace(BS + "pgfplotsset{compat=1.17}", "")
    width = "full width (7.16 in)" if "full width" in raw.split("\n")[0] else "one column (3.5 in)"
    pages.append(
        BS + "clearpage\n{\\noindent\\textbf{" + name.replace("_", BS + "_") + "}\\hfill\\textit{" + width + "}\\par\\medskip\n"
        + "{" + local + "\n" + body.strip() + "\n}}\n"
    )

doc = [
    r"% AUTO-GENERATED by scripts/make_preview.py -- do not edit; edit figures/*.tex and re-run the script.",
    r"% Preview of all figures in one compile. The per-figure PDFs still come from compiling each figures/figNN_*.tex.",
    r"\documentclass[10pt]{article}",
    r"\usepackage[letterpaper,margin=0.5in]{geometry}",
    r"\usepackage[T1]{fontenc}",
    r"\usepackage{newtxtext,newtxmath}",
    r"\usepackage{tikz}",
    r"\usepackage{pgfplots}",
    r"\pgfplotsset{compat=1.17}",
    r"\usetikzlibrary{" + ",".join(sorted(libs)) + "}",
    *color_lines,
    r"\pagestyle{empty}",
    r"\setlength{\parindent}{0pt}",
    r"\begin{document}",
    *pages,
    r"\end{document}",
    "",
]
out = os.path.join(PAPER, "figures_preview.tex")
open(out, "w", encoding="utf-8").write("\n".join(doc))
print(f"wrote {os.path.normpath(out)} with {len(pages)} figures; libraries: {sorted(libs)}")
